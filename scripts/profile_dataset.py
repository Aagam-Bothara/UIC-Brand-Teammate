"""Profile Team8Dataset.xlsx (sheet "Communications_Review") into a Markdown summary.

The workbook is treated as read-only. Requires openpyxl (not in requirements.txt),
so run it with any Python that has openpyxl installed, e.g.:

    python -I scripts/profile_dataset.py ~/Downloads/Team8Dataset.xlsx data/demo/DATASET_PROFILE.md

Only the standard library and openpyxl are imported.
"""
from __future__ import annotations

import sys
from collections import Counter, defaultdict
from statistics import mean

import openpyxl

SHEET = "Communications_Review"
DETAIL_COLS = {
    "Brand": "brand_issues_details",
    "Accessibility": "accessibility_issues_details",
    "Content": "content_issues_details",
}
STATUS_ORDER = ["Approved", "Minor Revisions Needed", "Major Revisions Needed", "Rejected - Full Rewrite"]


def load_rows(path: str):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    ws = wb[SHEET]
    it = ws.iter_rows(values_only=True)
    header = [str(h) for h in next(it)]
    rows = []
    for values in it:
        if all(v is None for v in values):
            continue
        rows.append(dict(zip(header, values)))
    wb.close()
    return header, rows


def split_issues(value) -> list:
    if value is None:
        return []
    value = str(value).strip()
    if not value or value == "None":
        return []
    return [s.strip() for s in value.split(";") if s.strip()]


def counter_table(counter: Counter, label: str, total: int) -> list:
    lines = [f"| {label} | Count | % |", "|---|---:|---:|"]
    for key, n in counter.most_common():
        lines.append(f"| {key} | {n} | {100 * n / total:.1f}% |")
    return lines


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 2
    xlsx_path, out_path = argv[1], argv[2]
    header, rows = load_rows(xlsx_path)
    n = len(rows)

    out = [
        "# Team8Dataset profile",
        "",
        f"Generated by `scripts/profile_dataset.py` from `Team8Dataset.xlsx`, sheet `{SHEET}`: "
        f"**{n} rows, {len(header)} columns**. The dataset holds metadata and issue labels only "
        "(no message text), which is why the demo drafts in `demo_drafts.json` were written by hand.",
        "",
        f"Draft dates range from {str(min(r['draft_date'] for r in rows))[:10]} "
        f"to {str(max(r['draft_date'] for r in rows))[:10]}. "
        f"Word count ranges from {min(r['word_count'] for r in rows)} to {max(r['word_count'] for r in rows)} "
        f"(mean {mean(r['word_count'] for r in rows):.0f}).",
        "",
    ]

    for col, label in [
        ("compliance_status", "Compliance status"),
        ("communication_type", "Communication type"),
        ("target_audience", "Target audience"),
        ("distribution_channel", "Distribution channel"),
        ("department", "Department"),
        ("author_role", "Author role"),
    ]:
        out += [f"## {label}", ""]
        out += counter_table(Counter(r[col] for r in rows), label, n)
        out.append("")

    out += ["## Averages by compliance status", "",
            "| Status | Rows | Brand score | Accessibility score | FK grade | Total issues | "
            "Manual review (min) | AI review (s) | Time savings (min) |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    by_status = defaultdict(list)
    for r in rows:
        by_status[r["compliance_status"]].append(r)
    statuses = [s for s in STATUS_ORDER if s in by_status] + sorted(set(by_status) - set(STATUS_ORDER))
    for s in statuses + ["All"]:
        rs = rows if s == "All" else by_status[s]
        out.append(
            f"| {'**All**' if s == 'All' else s} | {len(rs)} "
            f"| {mean(r['brand_compliance_score'] for r in rs):.1f} "
            f"| {mean(r['accessibility_score'] for r in rs):.1f} "
            f"| {mean(r['flesch_kincaid_grade_level'] for r in rs):.1f} "
            f"| {mean(r['total_issues_flagged'] for r in rs):.1f} "
            f"| {mean(r['manual_review_time_minutes'] for r in rs):.1f} "
            f"| {mean(r['ai_review_time_seconds'] for r in rs):.1f} "
            f"| {mean(r['time_savings_minutes'] for r in rs):.1f} |"
        )
    out.append("")

    out += ["### Total issues flagged, by status", "", "| Status | min | max | distribution (issues: rows) |",
            "|---|---:|---:|---|"]
    for s in statuses:
        c = Counter(r["total_issues_flagged"] for r in by_status[s])
        dist = ", ".join(f"{k}: {v}" for k, v in sorted(c.items()))
        out.append(f"| {s} | {min(c)} | {max(c)} | {dist} |")
    out.append("")
    out.append(
        "Note: the dataset's status labels do not follow the SPEC thresholds strictly. For example, "
        "some \"Approved\" rows have accessibility scores in the 70s and some \"Major Revisions Needed\" "
        "rows have only 1-2 issues."
    )
    out.append("")

    out += ["## Issue vocabulary", "",
            "Issue details are `; `-separated strings; `None` means no issues. Frequencies count rows.", ""]
    for label, col in DETAIL_COLS.items():
        c = Counter()
        rl_grades = Counter()
        for r in rows:
            for issue in split_issues(r[col]):
                if issue.startswith("Reading level at Grade"):
                    rl_grades[issue] += 1
                    c["Reading level at Grade N (grouped)"] += 1
                else:
                    c[issue] += 1
        empty = sum(1 for r in rows if not split_issues(r[col]))
        out += [f"### {label} ({len(c)} distinct, {empty} rows with none)", "",
                "| Issue | Rows |", "|---|---:|"]
        for issue, k in c.most_common():
            out.append(f"| {issue} | {k} |")
        if rl_grades:
            grades = sorted(float(g.rsplit(" ", 1)[1]) for g in rl_grades.elements())
            out.append("")
            out.append(
                f"\"Reading level at Grade N\" appears with {len(rl_grades)} distinct N values "
                f"({grades[0]}–{grades[-1]})."
            )
        out.append("")

    total_issue_rows = sum(1 for r in rows if r["total_issues_flagged"] == 0)
    out += ["## Other fields", "",
            f"- Rows with zero issues: {total_issue_rows}",
            f"- `ai_rewrite_offered`: {dict(Counter(r['ai_rewrite_offered'] for r in rows))}",
            f"- `published`: {dict(Counter(r['published'] for r in rows))}",
            f"- Mean images per item: {mean(r['image_count'] for r in rows):.1f}; "
            f"mean links: {mean(r['link_count'] for r in rows):.1f}",
            ""]

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"Wrote {out_path} ({n} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
